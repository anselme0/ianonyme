import { readFileSync } from 'node:fs';
import { extractFile } from '../src/main/extract/index.js';
import { createState, ingestText, mask } from 'engine';
const f = process.argv[2]!;
let t0 = Date.now();
const r = await extractFile(f, new Uint8Array(readFileSync(`../../demo/${f}`)), 10_000_000);
console.log('extract ms', Date.now() - t0, r.text.length, JSON.stringify(r.warnings));
t0 = Date.now();
const { state, conflicts } = ingestText(createState(), r.text);
console.log('ingest ms', Date.now() - t0);
console.log(mask(r.text, state).masked);
console.log('conflits', conflicts.length, Object.values(state.entities).map((e) => e.placeholder + ' ' + e.canonical).join(' | '));
process.exit(0);
